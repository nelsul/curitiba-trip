@Composable
fun Icon(name: IconName, tint: Color, modifier: Modifier = Modifier, size: Dp = 22.dp) {
	androidx.compose.material3.Icon(painterResource(name.res), contentDescription = null, tint = tint, modifier = modifier.size(size))
}

private val heartPath = PathParser().parsePathString("M12 20s-7-4.4-7-10a4 4 0 0 1 7-2.6A4 4 0 0 1 19 10c0 5.6-7 10-7 10z").toPath()

/** The heart, outlined or filled (same shape as the icon set). */
@Composable
fun HeartShape(filled: Boolean, color: Color, modifier: Modifier = Modifier, size: Dp = 26.dp) {
	Canvas(modifier.size(size)) {
		scale(this.size.width / 24f, pivot = androidx.compose.ui.geometry.Offset.Zero) {
			if (filled) drawPath(heartPath, color)
			drawPath(heartPath, color, style = Stroke(width = 2.3f, cap = StrokeCap.Round, join = StrokeJoin.Round))
		}
	}
}
